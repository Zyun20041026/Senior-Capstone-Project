/*
 * Build js/levels.js: for every strain, the neighbour table of its shell and
 * five layouts of resistant proteins, each proven solvable without a guess.
 *   node tools/generate.js            write js/levels.js
 *   node tools/generate.js --dry      only print what would be chosen
 * Node built-ins only. Deterministic: the same code gives the same file.
 */
const fs = require('fs');
const path = require('path');
const C = require('../js/core.js');
const Boards = require('../js/boards.js');
const Rules = require('../js/rules.js');
const Viruses = require('../js/viruses.js');

const DRY = process.argv.includes('--dry');

function fits(st, want, n, mines) {
  const share = st.open / (n - mines);
  return share >= want.open[0] && share <= want.open[1] && st.t2 >= want.t2 && st.t2 <= want.maxT2 && st.t3 >= want.t3 && st.t3 <= want.maxT3 && st.core <= want.core;
}
// how close a proven layout is to what the strain asks for (higher is closer)
function score(st, want, n, mines) {
  const share = st.open / (n - mines);
  let s = Math.min(st.t2, want.t2) + 4 * Math.min(st.t3, want.t3);
  s -= 3 * Math.max(0, st.t2 - want.maxT2) + 6 * Math.max(0, st.t3 - want.maxT3);
  if (st.core > want.core) s -= 20;
  s -= 30 * (Math.max(0, want.open[0] - share) + Math.max(0, share - want.open[1]));
  return s;
}

// Random layouts on these shells are almost always solvable with one reading
// at a time, so start from any proven layout and move one resistant protein
// at a time, keeping every move that stays provable and is no further from
// the wanted depth of reasoning.
function layouts(v, adj, seed) {
  const n = adj.length, rnd = C.rng32(seed), out = [], used = new Set();
  let proofs = 0, restarts = 0;
  while (out.length < Viruses.VARIANTS) {
    if (++restarts > 4000) throw new Error(v.id + ': could not find enough layouts');
    const start = Math.floor(rnd() * n);
    if (used.has(start)) continue;
    const banned = new Set([start].concat(adj[start])), pool = [];
    for (let i = 0; i < n; i++) if (!banned.has(i)) pool.push(i);
    C.shuffle(pool, rnd);
    let mines = pool.slice(0, v.mines), res = Rules.prove(adj, mines, start);
    proofs++;
    if (!res.solved) continue;
    let cur = score(res.stats, v.want, n, v.mines);
    for (let it = 0; it < 500 && !fits(res.stats, v.want, n, v.mines); it++) {
      const has = new Set(mines), free = pool.filter((i) => !has.has(i));
      const next = mines.slice();
      next[Math.floor(rnd() * next.length)] = free[Math.floor(rnd() * free.length)];
      const r2 = Rules.prove(adj, next, start);
      proofs++;
      if (!r2.solved) continue;
      const s2 = score(r2.stats, v.want, n, v.mines);
      if (s2 >= cur) { mines = next; res = r2; cur = s2; }
    }
    if (!fits(res.stats, v.want, n, v.mines)) continue;
    used.add(start);
    adj[start].forEach((j) => used.add(j));       // spread the first doses around the shell
    out.push({ start, mines: mines.slice().sort((a, b) => a - b), stats: res.stats });
  }
  return { out, proofs, restarts };
}

const levels = [];
Viruses.LIST.forEach((v, li) => {
  const t = Date.now(), board = Boards.build(v.board), adj = board.adj;
  const r = layouts(v, adj, 1000 + li * 7919);
  levels.push({ id: v.id, cells: adj.length, mines: v.mines, adj, variants: r.out });
  console.log(v.id.padEnd(7), 'cells', String(adj.length).padStart(3), 'resistant', String(v.mines).padStart(2), (v.mines / adj.length * 100).toFixed(1) + '%',
    'proofs', r.proofs, 'restarts', r.restarts, (Date.now() - t) + 'ms');
  r.out.forEach((x) => console.log('   start', String(x.start).padStart(3), 'open', (x.stats.open / (adj.length - v.mines) * 100).toFixed(0) + '%', 'rounds', x.stats.rounds, 't1', x.stats.t1, 't2', x.stats.t2, 't3', x.stats.t3, 'core', x.stats.core));
});

